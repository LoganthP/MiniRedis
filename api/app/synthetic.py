"""Synthetic e-commerce dataset (CC0) shaped like the Olist public dataset.

Use it for demos you will show or distribute: Olist on Kaggle is
CC BY-NC-SA 4.0 (non-commercial), so it must not be bundled with a product.

    python -m app.synthetic out.zip --products 1000 --orders 5000

The ZIP contains:
  products.csv                  product_id, product_category_name, ... (Olist-like columns)
  orders.jsonl                  one JSON object per line
  reviews.json                  JSON Lines despite the .json extension (like Yelp's files)
  categories.json               a JSON array
  README.txt / LICENSE.txt      provenance (synthetic, CC0)
  extras/product_photos.xlsx    deliberately unsupported, to show how it is reported
"""
from __future__ import annotations

import argparse
import csv
import io
import json
import random
import zipfile
from datetime import datetime, timedelta

CATEGORIES = [
    "cama_mesa_banho", "beleza_saude", "esporte_lazer", "moveis_decoracao", "informatica_acessorios",
    "utilidades_domesticas", "relogios_presentes", "telefonia", "ferramentas_jardim", "automotivo",
    "brinquedos", "cool_stuff", "perfumaria", "bebes", "eletronicos",
]
STATUSES = ["delivered"] * 90 + ["shipped"] * 4 + ["canceled"] * 2 + ["invoiced"] * 2 + ["processing"] * 2


def _hex(rng: random.Random, n: int = 32) -> str:
    return "".join(rng.choice("0123456789abcdef") for _ in range(n))


def build(products: int = 1000, orders: int = 5000, seed: int = 42) -> bytes:
    rng = random.Random(seed)
    weights = [1 / (i + 1) ** 0.8 for i in range(len(CATEGORIES))]
    prods = []
    for _ in range(products):
        cat = rng.choices(CATEGORIES, weights)[0]
        prods.append({
            "product_id": _hex(rng),
            "product_category_name": cat,
            "product_name_lenght": rng.randint(20, 64),
            "product_description_lenght": rng.randint(100, 3000),
            "product_photos_qty": rng.randint(1, 6),
            "product_weight_g": rng.randint(100, 20000),
            "price": round(rng.lognormvariate(4.2, 0.8), 2),
        })
    start = datetime(2017, 1, 1)
    ords = []
    for _ in range(orders):
        p = prods[min(int(rng.paretovariate(1.1)) - 1, len(prods) - 1)]
        ts = start + timedelta(days=rng.random() * 600 * (0.4 + rng.random() * 0.6))
        ords.append({
            "order_id": _hex(rng),
            "customer_id": _hex(rng),
            "order_status": rng.choice(STATUSES),
            "order_purchase_timestamp": ts.strftime("%Y-%m-%d %H:%M:%S"),
            "product_id": p["product_id"],
            "price": p["price"],
            "freight_value": round(rng.uniform(5, 60), 2),
        })
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        s = io.StringIO()
        w = csv.DictWriter(s, fieldnames=list(prods[0]))
        w.writeheader()
        w.writerows(prods)
        zf.writestr("products.csv", s.getvalue())
        zf.writestr("orders.jsonl", "".join(json.dumps(o) + "\n" for o in ords))
        reviews = [{"review_id": _hex(rng), "order_id": o["order_id"], "review_score": rng.choices([1, 2, 3, 4, 5], [1, 1, 2, 4, 8])[0]}
                   for o in ords[: max(1, len(ords) // 2)]]
        zf.writestr("reviews.json", "".join(json.dumps(r) + "\n" for r in reviews))
        zf.writestr("categories.json", json.dumps([{"category_id": i, "product_category_name": c} for i, c in enumerate(CATEGORIES)]))
        zf.writestr("README.txt", "Synthetic e-commerce data generated by MiniRedis (app/synthetic.py).\n"
                                  "Columns mirror the Olist Brazilian E-Commerce dataset, but every value is random.\n")
        zf.writestr("LICENSE.txt", "CC0 1.0 — no rights reserved. Safe to bundle and redistribute.\n")
        zf.writestr("extras/product_photos.xlsx", b"PK\x03\x04 not a real workbook")
    return buf.getvalue()


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--products", type=int, default=1000)
    ap.add_argument("--orders", type=int, default=5000)
    a = ap.parse_args()
    with open(a.out, "wb") as f:
        f.write(build(a.products, a.orders))
    print(f"wrote {a.out}")
