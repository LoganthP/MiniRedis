import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { defineConfig, type Plugin } from "vite";
import react from "@vitejs/plugin-react";
import tailwindcss from "@tailwindcss/vite";

// In development the dashboard calls /api/* on the Vite server, which forwards
// to the FastAPI service. In Docker, nginx does the same forwarding.
//
// Static hosts (Netlify, Cloudflare Pages) read a `_redirects` file from the
// build output. When MINIREDIS_API_URL is set at build time (for example
// https://miniredis-backend.onrender.com) the build writes a proxy rule so the
// site's /api/* goes to that backend; the browser stays on one origin, so no
// CORS setup is needed. Without it, /api/* is answered by the host itself and
// the dashboard shows a "No backend" banner.
function staticHostRedirects(): Plugin {
  return {
    name: "static-host-redirects",
    apply: "build",
    closeBundle() {
      const api = (process.env.MINIREDIS_API_URL ?? "").trim().replace(/\/+$/, "");
      const lines = ["# generated by vite.config.ts"];
      if (api) {
        if (!/^https?:\/\//.test(api)) throw new Error(`MINIREDIS_API_URL must start with http(s)://, got ${api}`);
        lines.push(`/api/*  ${api}/api/:splat  200!`);
      } else {
        lines.push("# MINIREDIS_API_URL was not set at build time: no /api proxy.");
      }
      lines.push("/*  /index.html  200");
      writeFileSync(resolve(__dirname, "dist/_redirects"), lines.join("\n") + "\n");
    },
  };
}

export default defineConfig({
  plugins: [react(), tailwindcss(), staticHostRedirects()],
  server: {
    port: 5173,
    proxy: { "/api": { target: process.env.API_URL ?? "http://127.0.0.1:8000", changeOrigin: true } },
  },
  preview: {
    port: 4173,
    proxy: { "/api": { target: process.env.API_URL ?? "http://127.0.0.1:8000", changeOrigin: true } },
  },
});
